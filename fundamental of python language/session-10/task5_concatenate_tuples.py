# Purpose: Concatenate fav_apps and new_apps into a single tuple called all_apps.
# ==============================================================================

# First tuple
fav_apps = ('Instagram', 'Zomato', 'Spotify', 'WhatsApp', 'Flipkart')

# Second tuple with 2 new apps to try
new_apps = ('Netflix', 'Amazon')

# Concatenate (combine) both tuples using the + operator
all_apps = fav_apps + new_apps

# Print the results
print("Favorite Apps :", fav_apps)
print("New Apps      :", new_apps)
print("\nAll Apps (Combined):")
print(all_apps)

