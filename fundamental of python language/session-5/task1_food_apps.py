# 1. Create a list containing 5 food delivery apps
food_apps = ["Zomato", "Swiggy", "Domino's", "McDonald's", "Pizza Hut"]

# 2. Use a for loop to go through the list one app at a time
print("Five Food Delivery Apps:")
for app in food_apps:
    print(app)

