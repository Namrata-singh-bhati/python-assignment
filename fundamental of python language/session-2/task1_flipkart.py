# Step 1: Create the variables
product_name = "Wireless Bluetooth Headphones"  # Text (str - String)
price = 1499.00                                # Decimal number (float)
is_available = True                            # Yes/No value (bool - Boolean)
rating = 4.5                                   # Decimal number (float)

# Step 2: Print each variable along with its data type using type()
print("Product Name :", product_name)
print("Data Type    :", type(product_name))
print()

print("Price        :", price)
print("Data Type    :", type(price))
print()

print("Is Available :", is_available)
print("Data Type    :", type(is_available))
print()

print("Rating       :", rating)
print("Data Type    :", type(rating))

