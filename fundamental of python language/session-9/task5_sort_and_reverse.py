my_fav_apps = ['Instagram', 'WhatsApp', 'Zomato', 'Spotify', 'YouTube']

# 1. Sort in alphabetical order (A-Z) using the list method sort()
my_fav_apps.sort()
print("Alphabetical order (A to Z) using sort():")
print(my_fav_apps)

# 2. Reverse the list order (Z-A) using the list method reverse()
my_fav_apps.reverse()
print("\nReversed order (Z to A) using reverse():")
print(my_fav_apps)

